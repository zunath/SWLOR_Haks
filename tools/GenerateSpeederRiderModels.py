#!/usr/bin/env python3
"""Generate the speeder riding phenotypes: animation banks, body roots and robes.

A mounted rider switches to phenotype 22. Body parts fall back to phenotype 0 through
phenotype.2da DefaultPhenoType, but three kinds of model must exist per riding
phenotype:

* an animation bank that replaces locomotion and idle clips with the seated
  pose and inherits every other clip from the ordinary bank;
* a body root for each race and gender whose supermodel is that bank;
* a copy of every robe whose supermodel is the riding root or bank. A robe
  animates through its own supermodel chain, so the base-phenotype robe would
  keep standing and running while the body sits.

Robes retain their original geometry, skin bindings and tint materials; names
and inherited animation part IDs are remapped to the mounted chain. The riding
models keep the complete skeleton of the model they replace because the
compiler matches part IDs against the immediate parent's tree only.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import struct
import tempfile

import CompileModels as mdl
import GenerateTintMapAssets as tint
import RobeAnimations as anim
import RobePoseAudit as poses
from ModelLodAssets import rename_identity

ROOT = Path(__file__).resolve().parents[1]
POSE = json.loads((ROOT / "tools" / "SpeederRiderPose.json").read_text(encoding="utf8"))
BANK_DIRECTORY = ROOT / "sw_cr_creature"
ROOT_DIRECTORY = ROOT / "sw_pt_root"
ROBE_DIRECTORY = ROOT / "sw_pt_robe"
STOCK_ROBES = ROOT / "tools" / "SpeederRiderStockRobes.json"
HEADER = "# SWLOR speeder rider model generated by tools/GenerateSpeederRiderModels.py\n"
# Base phenotype -> riding phenotype. Keep in step with phenotype.2da and SpeederItemDefinition.
PHENOTYPES = {"0": "22"}
# Animation banks used directly by robes or body roots, and their riding replacements.
BANKS = {
    "a_ba": "a_ba_rd", "a_fa": "a_fa_rd", "a_da": "a_da_rd", "a_dfa": "a_dfa_rd",
    "a_ba_coat": "a_ba_coat_rd", "a_fa_coat": "a_fa_coat_rd", "a_da_coat": "a_da_coat_rd",
    "a_dfa_coat": "a_dfa_coat_rd", "a_fa_skirt": "a_fa_skirt_rd", "a_ba_non_combat": "a_ba_noncmb_rd",
    "hss_pmh0": "hss_pmh0_rd", "hss_pfh0": "hss_pfh0_rd",
}
# Preserve the current race-specific rifle animation chain underneath riding clips.
RIFLE_BODIES = ("pfd0", "pfe0", "pfh0", "pfo0", "pfz0", "pmd0", "pme0", "pmo0", "pmz0")
BANKS.update({"a_rfl_" + body: "a_rd_" + body for body in RIFLE_BODIES})
FEMALE_BANKS = {"a_fa", "a_dfa", "a_fa_coat", "a_dfa_coat", "a_fa_skirt", "hss_pfh0"}
FEMALE_BANKS.update("a_rfl_" + body for body in RIFLE_BODIES if body[1] == "f")
REFERENCE_BANK = {"male": "a_ba", "female": "a_fa"}
# Clips a mounted character can reach. Everything else is inherited unchanged.
FULL_BODY_CLIPS = (
    "pause1", "pause2", "pausebrd", "pausepsn", "pausesh", "pausetrd", "pauseturn", "plpause1",
    "pausewalkl", "pausewalkr", "pausewalkfl", "pausewalkfr", "walk", "run", "runfl", "runfr",
    "walkinj", "walkdead", "cwalkf", "cwalkb", "cwalkl", "cwalkr", "cturnr",
    "1hreadyl", "1hreadyr", "2hreadyl", "2hreadyr", "2wreadyl", "2wreadyr", "nwreadyl", "nwreadyr",
    "plreadyl", "plreadyr", "tlknorm", "tlkplead", "tlkforce", "tlklaugh", "listen", "hturnl", "hturnr",
    "getmid", "getmidlp", "getlow", "getlowlp",
)
# Carry overlays animate one arm while the body runs; keep both hands on the controls instead.
OVERLAY_CLIPS = {
    "walk_swordr": "rbicep_g", "run_swordr": "rbicep_g", "walk_swordl": "lbicep_g", "run_swordl": "lbicep_g",
    "walk_bowl": "lbicep_g", "run_bowl": "lbicep_g", "walk_shieldl": "lbicep_g", "run_shieldl": "lbicep_g",
}
CLIPS = {**{clip: "rootdummy" for clip in FULL_BODY_CLIPS}, **OVERLAY_CLIPS}
ROBE = re.compile(r"^(p[mf][a-z])(0)_robe(\d+)$")
BODY = re.compile(r"^(p[mf][a-z])(0)$")
# Fit the existing bike to the different humanoid skeleton proportions.
# SpeederAppearance applies the matching CreatureTail scale; NWN ignores dummy scale.
VEHICLE_SCALES = {"a": .7, "b": 1.2, "d": .8, "e": .9, "g": .6, "h": 1.0, "o": 1.25, "z": 1.0}


def number(value):
    return format(value, ".7g")


def riding_name(name):
    """Riding replacement for a robe's or root's supermodel; None keeps the original."""
    body = BODY.match(name)
    if body:
        return body[1] + PHENOTYPES[body[2]]
    # These legacy robe parents never shipped; the same-gender HSS skeleton
    # supplies their garment joints. The robe retains its own proportions.
    aliases = {"hss_pmd0": "hss_pmh0", "hss_pfd0": "hss_pfh0"}
    return BANKS.get(aliases.get(name, name))


def bank_source(name, parent, text):
    """Animation-only model holding the seated clips over the parent's complete skeleton."""
    gender = "female" if parent in FEMALE_BANKS else "male"
    pose = POSE[gender]
    nodes = {name: {"parent": ["null"]}, **anim.skeleton(text, [], name)}
    ordered = anim.order_nodes(nodes, name)
    if any(bone not in nodes for bone in ("rootdummy", "torso_g", "pelvis_g")):
        raise ValueError(f"{parent}: not a humanoid body skeleton")
    keys = {}
    # Garment banks carry partial skeletons; a robe only binds to the bones its bank has.
    garment = POSE["garment"]
    rotations = {**pose["bones"], **garment["rotations"],
                 **{panel: pose["bones"][bone] for panel, bone in garment["follow"].items()}}
    for bone, rotation in rotations.items():
        if bone not in nodes:
            continue
        row = [number(value) for value in rotation]
        keys[bone] = {"orientationkey": [["0", *row], ["1", *row]]}
    return nodes, ordered, keys, pose


def bank_model(name, parent, text, reference_height):
    nodes, ordered, keys, pose = bank_source(name, parent, text)
    bind = [float(value) for value in nodes["rootdummy"].get("position", ["0", "0", "0"])]
    # Seat height follows the skeleton's own leg length; each wearer's animation scale applies on top.
    height = pose["root"][2] * bind[2] / reference_height
    row = [number(pose["root"][0]), number(pose["root"][1]), number(height)]
    keys["rootdummy"] = {"positionkey": [["0", *row], ["1", *row]]}
    output = (HEADER + f"newmodel {name}\nsetsupermodel {name} {parent}\nclassification CHARACTER\n"
              f"setanimationscale 1\nbeginmodelgeom {name}\n" +
              "".join(anim.serialize_node(node, props) for node, props in ordered) + f"endmodelgeom {name}\n")
    for clip, animation_root in CLIPS.items():
        if animation_root not in nodes:
            continue
        clip_nodes = "".join(anim.serialize_node(node, {"parent": props["parent"], **keys.get(node, {})})
                             for node, props in ordered)
        output += (f"newanim {clip} {name}\n  length 1\n  transtime 0.25\n  animroot {animation_root}\n"
                   f"{clip_nodes}doneanim {clip} {name}\n")
    return (output + f"donemodel {name}\n").encode("latin1")


def level_tail(text):
    """Anchor the vehicle to the body root, independent of the seated pelvis tilt."""
    owner = anim.model_name(text)
    block = f"node dummy tail\n  parent {owner}\n  position 0 -0.08 0\n  orientation 0 0 1 0\n  scale 1\nendnode"
    result, count = re.subn(r"(?ims)^\s*node\s+\S+\s+tail\s*$.*?^\s*endnode\b", "", text)
    if count != 1:
        raise ValueError("Body root must have exactly one tail attachment")
    return re.sub(r"(?im)^endmodelgeom", lambda m: block + "\n" + m[0], result, count=1)


def root_model(name, base_name, text, parent):
    """The base body root under a new name, animated by the riding bank."""
    # Race-specific clips stay with the base root; the riding bank supplies the mounted ones.
    body = text.split("newanim", 1)[0] if re.search(r"(?im)^\s*newanim\b", text) else text
    body = level_tail(body)
    body = re.sub(rf"(?i)(?<![\w.]){re.escape(base_name)}(?![\w.])", name, body)
    body, count = re.subn(r"(?im)^(\s*setsupermodel\s+\S+\s+)\S+", rf"\g<1>{parent}", body)
    if count != 1:
        raise ValueError(f"{base_name}: expected one supermodel declaration")
    if not re.search(r"(?im)^\s*donemodel\b", body):
        body = body.rstrip() + f"\ndonemodel {name}\n"
    return (HEADER + body).encode("latin1")


def fit_vehicle(data, name, load):
    """Keep the bike level and fit its saddle to the seated body's height."""
    body = poses.Model(data)
    bank = poses.Model(load(body.parent))
    seated = body.pose(bank.clips["pause1"], translation_scale=body.scale / bank.scale)
    root = seated["rootdummy"][0]
    scale = VEHICLE_SCALES[name[2]]
    reference = POSE["male"]["root"]
    position = (0, root[1] - scale * (reference[1] + .08), root[2] - scale * reference[2])
    tail = next(node for node in body.nodes if node[0] == "tail")
    offset = tail[4]
    result = bytearray(data)
    for index in range(body.uint(offset + 88)):
        kind, _, _, start, _ = struct.unpack_from("<IHHHB", data, 12 + body.uint(offset + 84) + index * 12)
        value = 12 + body.uint(offset + 96) + start * 4
        if kind == 8:
            struct.pack_into("<3f", result, value, *position)
        elif kind == 36:
            struct.pack_into("<f", result, value, scale)
    return bytes(result)


def inherited_parts(name, load):
    """Animation part ID of every node path, taken from the nearest compiled ancestor that has it."""
    result = {}
    seen = set()
    while name and name not in seen:
        seen.add(name)
        data = load(name)
        if data is None:
            break
        if mdl.binary(data):
            for path, part in anim.binary_parts(data).items():
                if part >= 0:
                    result.setdefault(path, part)
        name = mdl.supermodel(data)
    return result


def match_inherited_parts(compiled, load):
    """Number a riding root's joints the way the clips above its bank expect.

    The compiler matches part IDs against the immediate parent only. The
    short-legged banks lack cloak and belt joints, so those received fresh IDs
    and the clips inherited from further up the chain would stop reaching them.
    """
    result = bytearray(compiled)
    expected = inherited_parts(mdl.supermodel(compiled), load)
    actual = anim.binary_parts(compiled)
    remap = {}
    for path, part in actual.items():
        if part >= 0 and path in expected and expected[path] >= 0:
            target = expected[path]
            if remap.setdefault(part, target) != target:
                raise ValueError(f"Ambiguous inherited part ID: {path}")
    occupied = {part for part in expected.values() if part >= 0}
    next_part = max([*actual.values(), *expected.values(), 0]) + 1
    for part in sorted(set(actual.values()) - remap.keys() - {-1}):
        if part in occupied:
            remap[part] = next_part
            next_part += 1
    uint = lambda offset: struct.unpack_from("<I", compiled, offset)[0]
    def visit(pointer):
        offset = pointer + 12
        part = struct.unpack_from("<i", compiled, offset + 28)[0]
        if part in remap:
            struct.pack_into("<i", result, offset + 28, remap[part])
        for index in range(uint(offset + 76)):
            visit(uint(12 + uint(offset + 72) + index * 4))
    visit(uint(84))
    for index in range(uint(136)):
        animation = 12 + uint(12 + uint(132) + index * 4)
        visit(uint(animation + 72))
    def inherited_attachments(pointer, path):
        offset = pointer + 12
        current = (*path, fixed(compiled, offset + 32, 32)) if path is not None else ()
        if current and actual.get(current, -1) < 0 and expected.get(current, -1) >= 0:
            struct.pack_into("<i", result, offset + 28, expected[current])
        for index in range(uint(offset + 76)):
            inherited_attachments(uint(12 + uint(offset + 72) + index * 4), current)
    inherited_attachments(uint(84), None)
    # Some legacy robes carry unrelated private clips with unmatched wrapper paths.
    # Preserve those byte-for-byte apart from the same ID remap used by their geometry.
    # A valid source must remain valid; the mounted tracks are checked against the
    # target parent independently for every generated robe.
    try:
        anim.validate_animation_parts(compiled)
    except ValueError:
        pass
    else:
        anim.validate_animation_parts(bytes(result))
    return bytes(result)


def fixed(data, offset, size):
    return data[offset:offset + size].split(b"\0", 1)[0].decode("ascii").lower()


def rename_binary(data, old, new, parent, disabled_clips):
    """Copy a compiled robe under a new model name and supermodel, changing nothing else."""
    result = bytearray(data)
    uint = lambda offset: struct.unpack_from("<I", data, offset)[0]
    def put(offset, size, value):
        encoded = value.encode("ascii")
        if len(encoded) >= size:
            raise ValueError(f"{value}: name exceeds the {size}-byte field")
        result[offset:offset + size] = encoded.ljust(size, b"\0")
    def visit(pointer):
        node = 12 + pointer
        if fixed(data, node + 32, 32) == old:
            put(node + 32, 32, new)
        for index in range(uint(node + 76)):
            visit(uint(12 + uint(node + 72) + index * 4))
    # Some legacy robes were copied between styles without renaming their internal
    # model. Keep that mismatch: tint binding addresses the subtree by file name.
    internal = fixed(data, 20, 64)
    if internal != old:
        old, new = internal, (robe_copy_name(internal) if ROBE.match(internal) else internal)
    put(20, 64, new)
    put(180, 64, parent)
    visit(uint(84))
    for index in range(uint(136)):
        animation = 12 + uint(12 + uint(132) + index * 4)
        clip = fixed(data, animation + 8, 64)
        if clip in disabled_clips:
            # A robe's private copy of a locomotion clip would override the seated pose.
            put(animation + 8, 64, ("x" + clip)[:63])
        if fixed(data, animation + 84, 64) == old:
            put(animation + 84, 64, new)
        visit(uint(animation + 72))
    return bytes(result)


def rename_ascii(data, old, new, parent, disabled_clips):
    text = data.decode("latin1")
    text = re.sub(rf"(?i)(?<![\w.]){re.escape(old)}(?![\w.])", new, text)
    text = re.sub(r"(?im)^(\s*setsupermodel\s+\S+\s+)\S+", rf"\g<1>{parent}", text, count=1)
    for clip in disabled_clips:
        text = re.sub(rf"(?im)^(\s*(?:newanim|doneanim)\s+){re.escape(clip)}(\s)", rf"\g<1>x{clip}\2", text)
    return text.encode("latin1")


def robe_copy_name(name):
    match = ROBE.match(name)
    return f"{match[1]}{PHENOTYPES[match[2]]}_robe{match[3]}"


def robe_copy(name, data):
    new = robe_copy_name(name)
    parent = mdl.supermodel(data)
    target = riding_name(parent) or parent
    rename = rename_binary if mdl.binary(data) else rename_ascii
    return new, rename(data, name, new, target, set(CLIPS))


def append_riding_tint_rows(table, models):
    """Keep saved robe dyes addressable on mounted copies without replacing existing rows."""
    rows = []
    by_pair = {}
    for index, line in enumerate(table.decode("utf8").splitlines()[3:]):
        columns = line.split()
        if len(columns) != 4 or columns[0] != str(index):
            raise ValueError(f"tintmap.2da: invalid physical row {index}")
        _, model, material, layers = columns
        rows.append((model, material, layers))
        if model != "****":
            pair = (model, material)
            if pair in by_pair:
                raise ValueError(f"tintmap.2da: duplicate binding {model}/{material}")
            by_pair[pair] = layers
    additions = []
    bindings = {}
    for source, material, layers in rows:
        if not ROBE.fullmatch(source):
            continue
        mounted = robe_copy_name(source)
        if mounted not in models:
            continue
        if mounted not in bindings:
            bindings[mounted] = {name for _, _, _, name in
                tint.read_binary_model_material_fields(Path(mounted + ".mdl"), models[mounted]) if name}
        if material not in bindings[mounted]:
            raise ValueError(f"{mounted}: copied robe lacks source tint material {material}")
        pair = (mounted, material)
        if pair in by_pair:
            if by_pair[pair] != layers:
                raise ValueError(f"tintmap.2da: mounted binding {mounted}/{material} has different layers")
            continue
        by_pair[pair] = layers
        additions.append(f"{len(rows) + len(additions):<4} {mounted:<17} {material:<17} {layers}")
    if not additions:
        return table, 0
    newline = b"\r\n" if b"\r\n" in table else b"\n"
    separator = b"" if table.endswith(b"\n") else newline
    return table + separator + newline.join(line.encode("utf8") for line in additions) + newline, len(additions)


class Decompiler:
    def __init__(self, stage):
        self.stage = stage
        for folder in ("binary", "decompiled"):
            (stage / folder).mkdir(parents=True, exist_ok=True)
        self.compiler, _ = mdl.prepare_compiler(stage)

    def text(self, name, data):
        if not mdl.binary(data):
            return data.decode("latin1")
        (self.stage / "binary" / f"{name}.mdl").write_bytes(data)
        mdl.run_compiler(self.compiler, self.stage, ["-de", str(self.stage / "binary" / f"{name}.mdl"),
                                                     str(self.stage / "decompiled" / f"{name}.mdl")], f"{name}.log")
        return (self.stage / "decompiled" / f"{name}.mdl").read_text(encoding="latin1")


def plan(game_data, stage):
    """Every generated resource as {path: bytes}, plus the ASCII models that need compiling."""
    active = tint.find_active_models()
    stock = tint.read_stock_key_models(game_data)
    decompiler = Decompiler(stage)
    def load(name):
        if name in active:
            return active[name].read_bytes()
        if name in stock:
            return tint.extract_stock_bif_resource(*stock[name])
        return None
    sources, robes, stock_robes = {}, {}, []
    heights = {}
    for gender, reference in REFERENCE_BANK.items():
        nodes = anim.skeleton(decompiler.text(reference, load(reference)), [], "reference")
        heights[gender] = float(nodes["rootdummy"]["position"][2])
    for parent, name in BANKS.items():
        data = load(parent)
        if data is None:
            raise RuntimeError(f"Animation bank {parent} is absent from the HAK sources and the installed game")
        gender = "female" if parent in FEMALE_BANKS else "male"
        sources[BANK_DIRECTORY / f"{name}.mdl"] = bank_model(name, parent, decompiler.text(parent, data), heights[gender])
    for base_name in sorted(name for name in {*active, *stock} if BODY.match(name)):
        data = load(base_name)
        parent = mdl.supermodel(data)
        if parent not in BANKS:
            raise RuntimeError(f"{base_name}: no riding bank for supermodel {parent}")
        name = riding_name(base_name)
        sources[ROOT_DIRECTORY / f"{name}.mdl"] = root_model(name, base_name, decompiler.text(base_name, data), BANKS[parent])
    for base_name in sorted(name for name in {*active, *stock} if ROBE.match(name)):
        name, data = robe_copy(base_name, load(base_name))
        # Tint binding addresses nodes by compiled offsets, so ASCII robes are compiled like the banks.
        (robes if mdl.binary(data) else sources)[ROBE_DIRECTORY / f"{name}.mdl"] = data
        if base_name not in active:
            stock_robes.append(base_name)
    # Use the complete, textured bike already present in the asset repository.
    # The old tail refers to the absent speeder2 texture; keep it available unchanged.
    robes[BANK_DIRECTORY / "tail_spdr_rider.mdl"] = rename_identity(load("c_motojet"), "tail_spdr_rider")
    return sources, robes, stock_robes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-data", type=Path, required=True, help="Installed EE data directory, for stock roots, banks and robes")
    parser.add_argument("--apply", action="store_true", help="Write the generated models and compile the ASCII ones in place")
    args = parser.parse_args()
    stage = Path(tempfile.mkdtemp(prefix="swlor-speeder-models-"))
    sources, robes, stock_robes = plan(args.game_data, stage)
    riding = re.compile(rf"^p[mf][a-z](?:{'|'.join(PHENOTYPES.values())})_robe\d+\.mdl$")
    kept = {robe_copy_name(name) for name in stock_robes}
    stale = sorted(path.name for path in ROBE_DIRECTORY.iterdir()
                   if riding.match(path.name) and path not in robes and path not in sources and path.stem not in kept)
    if stale:
        raise ValueError(f"Mounted robes without source counterparts: {', '.join(stale)}")
    print(f"Validating {len(sources)} banks, body roots and ASCII robes; {len(robes)} binary models.", flush=True)
    active = tint.find_active_models()
    stock = tint.read_stock_key_models(args.game_data)
    planned = {path.stem: data for path, data in {**sources, **robes}.items()}
    compiled = {}
    dependency_cache = {}
    compiler, _ = mdl.prepare_compiler(stage)
    for folder in ("input", "binary", "decompiled"):
        (stage / folder).mkdir(exist_ok=True)
    visiting = set()

    def load(name):
        if name in compiled:
            return compiled[name]
        if name in planned:
            return planned[name]
        if name in dependency_cache:
            return dependency_cache[name]
        if name in active:
            dependency_cache[name] = active[name].read_bytes()
            return dependency_cache[name]
        if name in stock:
            dependency_cache[name] = tint.extract_stock_bif_resource(*stock[name])
            return dependency_cache[name]
        raise ValueError(f"Missing supermodel: {name}")

    def compile_one(name):
        if name in compiled:
            return compiled[name]
        if name in visiting:
            raise ValueError(f"Cyclic supermodel chain: {name}")
        visiting.add(name)
        data = load(name)
        parent = mdl.supermodel(data)
        if parent:
            compile_one(parent)
        if mdl.binary(data):
            output = data
        else:
            data, _ = mdl.repair_legacy_input(data)
            prepared = mdl.protect_vertex_identity(data)
            source = stage / "input" / (name + ".mdl")
            source.write_bytes(prepared)
            mdl.run_compiler(compiler, stage, ["-cne", str(source), str(stage / "binary") + "/"], name + "-compile.log")
            output = poses.repair_compiler_skin_bindings(mdl.restore_vertex_attributes(data,
                (stage / "binary" / (name + ".mdl")).read_bytes()))
            (stage / "binary" / (name + ".mdl")).write_bytes(output)
            mdl.run_compiler(compiler, stage, ["-de", str(stage / "binary" / (name + ".mdl")),
                str(stage / "decompiled") + "/"], name + "-decompile.log")
            mdl.validate_round_trip(data, output, (stage / "decompiled" / (name + ".mdl")).read_text(encoding="latin1"))
        if name in planned and re.fullmatch(r"p[fm][a-z]22(?:_robe\d+)?", name):
            output = match_inherited_parts(output, load)
        if name in planned and re.fullmatch(r"p[fm][a-z]22", name):
            output = fit_vehicle(output, name, load)
        compiled[name] = output
        (stage / (name + ".mdl")).write_bytes(output)
        visiting.remove(name)
        return output

    for name in planned:
        compile_one(name)
    changed = [path for path in {**sources, **robes}
               if not path.is_file() or path.read_bytes() != compiled[path.stem]]
    tint_table = ROOT / "sw_2da" / "tintmap.2da"
    updated_tints, added_tints = append_riding_tint_rows(tint_table.read_bytes(), compiled)
    if not args.apply:
        if changed:
            raise ValueError(f"{len(changed)} stale mounted models; run with --apply: {', '.join(path.name for path in changed[:20])}")
        if added_tints:
            raise ValueError(f"{added_tints} mounted tint bindings missing; run with --apply")
        print(f"Verified {len(planned)} mounted resources. Compiler evidence: {stage}")
        return
    # No production source is touched until the whole dependency closure compiles.
    for path in {**sources, **robes}:
        path.write_bytes(compiled[path.stem])
    if added_tints:
        tint_table.write_bytes(updated_tints)
    STOCK_ROBES.write_text(json.dumps(stock_robes, indent=2) + "\n", encoding="utf8", newline="\n")
